import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {BridgeClient} from '../src/client.mjs';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url))),c=new BridgeClient(path.join(root,'test-project'));
const call=async(a,p={})=>(await c.call(a,p)).result;
const db=(message,...args)=>call('editor.request',{package:'asset-db',message,args});
const checks=[];let passed=false;
const pass=s=>{checks.push(s);console.log('PASS '+s);};
const prefix=`db://assets/MCP_WorkflowAssets/ResourceCheck${Date.now()}`;
try{
  assert.equal((await call('status')).editorVersion,'3.8.8');
  assert.equal(await call('editor.request',{package:'scene',message:'query-dirty',args:[]}),false);
  const original=await call('asset.info',{asset:'db://assets/MCP_WorkflowAssets/robot.png'});
  const source=await call('asset.copy',{asset:original.uuid,url:prefix+'-source.png',expectedRevision:original.revision});
  assert.notEqual(source.uuid,original.uuid);
  const a=await call('asset.info',{asset:source.uuid});
  const before=(await db('query-asset-info',source.uuid)).subAssets;
  const moved=await call('asset.move',{asset:source.uuid,url:prefix+'-moved.png',expectedRevision:a.revision});
  assert.equal(moved.uuid,source.uuid);assert.equal(moved.identityPreserved,true);
  const after=(await db('query-asset-info',source.uuid)).subAssets;
  assert.deepEqual(Object.values(after).map(s=>s.uuid).sort(),Object.values(before).map(s=>s.uuid).sort());
  await call('asset.reimport',{asset:source.uuid,expectedRevision:a.revision});
  await assert.rejects(call('asset.move',{asset:source.uuid,url:prefix+'-stale.png',expectedRevision:'0'.repeat(64)}),/revision changed/);
  assert.equal(await db('query-asset-info',prefix+'-stale.png'),null);
  pass('native copy creates UUID, move preserves main/subasset identities, reimport and stale-write rejection verified');
  const target=await call('asset.copy',{asset:original.uuid,url:prefix+'-target.png',expectedRevision:original.revision});
  const from=Object.values(after).find(s=>s.type==='cc.SpriteFrame').uuid;
  const targetInfo=await db('query-asset-info',target.uuid),to=Object.values(targetInfo.subAssets).find(s=>s.type==='cc.SpriteFrame').uuid;
  const scene=await db('query-asset-info','db://assets/MCP_WorkflowDemo.scene');
  const frame=original.subAssets.find(s=>s.type==='cc.SpriteFrame').uuid;
  const content=(await fs.readFile(scene.file,'utf8')).split(frame).join(from);
  const url=prefix+'.scene';await call('asset.write',{url,content});
  const baseline=(await call('asset.info',{asset:url})).revision;
  const graph=await call('asset.graph',{asset:from,direction:'users',depth:1});
  assert.ok(graph.nodes.some(n=>n.url===url));assert.equal(graph.missing.length,0);
  const cached=await call('asset.graph',{asset:from,direction:'users',depth:1});assert.ok(cached.cachedQueries>0);
  const budget=await call('asset.graph',{asset:url,maxNodes:1,maxEdges:1});assert.equal(budget.truncated,true);
  pass('reverse references, warm dependency cache and graph budget reporting verified');
  const plan=await call('asset.replace.plan',{from,to});assert.equal(plan.blocked,false,JSON.stringify(plan));assert.equal(plan.assets.length,1);
  const applied=await call('asset.replace.apply',{planId:plan.planId});assert.equal(applied.references,1);
  assert.ok((await fs.readFile((await db('query-asset-info',url)).file,'utf8')).includes(to));
  assert.ok(!(await call('asset.graph',{asset:from,direction:'users',depth:1})).nodes.some(n=>n.url===url));
  const dry=await call('asset.restore',{backupId:applied.backupId,dryRun:true});assert.equal(dry.dryRun,true);
  await call('asset.restore',{backupId:applied.backupId});
  assert.equal((await call('asset.info',{asset:url})).revision,baseline);
  assert.ok((await call('asset.graph',{asset:from,direction:'users',depth:1})).nodes.some(n=>n.url===url));
  pass('replacement plan/apply persisted references, invalidated graph and backup restore recovered exact original source');
  passed=true;
}finally{
  await fs.writeFile(path.join(root,'artifacts/live-resource-check.json'),JSON.stringify({passed,time:new Date().toISOString(),fixturePrefix:prefix,checks},null,2));
  if(!passed)process.exitCode=1;
}
